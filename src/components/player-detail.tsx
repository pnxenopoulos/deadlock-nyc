function propertyIcon(name: string): string {
  return `/icons/properties/${name}.svg`;
}

// Souls as "X.Yk" (e.g. 6400 -> "6.4k"); 0 stays "0".
function formatSouls(value: number): string {
  if (value <= 0) return "0";
  return `${(value / 1000).toFixed(1)}k`;
}

const ITEM_PIXELS = 48;
const SLOT_COUNT = 10;
const ABILITY_PIXELS = 48;
// Abilities have three upgrade tiers; we render one segment per tier.
const ABILITY_TIERS = 3;
const TICKS_PER_SECOND = 64;

export function PlayerDetail({
  modifiersEnabled = true,
  onEnableModifiers,
  player,
  stats,
  items,
  abilities,
  abilityLevels,
  abilityCooldowns,
  modifiers,
  details,
  status,
  permanentBuffs,
  catalog,
  detailsLoading,
  detailsError,
  players,
  tick,
  regTick,
  onBack,
}: {
  modifiersEnabled?: boolean;
  onEnableModifiers?: () => void;
  player: PlayerInfo;
  stats: PlayerPosition | undefined;
  items: HeroItems | undefined;
  abilities: AbilitySlot[] | undefined;
  abilityLevels: Map<number, number> | undefined;
  /** Reconstructed cooldown + charge timeline per ability_id (active player). */
  abilityCooldowns?: Map<number, AbilityCooldown>;
  modifiers?: ModifierSpan[];
  details?: PlayerDetails;
  status?: PlayerStatus;
  permanentBuffs?: PickupTotals;
  catalog?: CatalogInfo;
  detailsLoading?: boolean;
  detailsError?: string;
  players?: PlayerInfo[];
  tick?: number;
  /** Current non-paused match tick, used by modifier countdowns. */
  regTick?: number;
  onBack: () => void;
}) {
  const portrait = heroPortraitUrl(player.hero_id);
  const teamLabel = TEAM_NAMES[player.team] ?? `Team ${player.team}`;
  const teamColor = TEAM_COLORS[player.team] ?? "#888";
  const visibleModifiers = React.useMemo(
    () => modifiers?.filter((modifier) => !isPermanentStatPickup(modifier) && !isIgnoredModifier(modifier.modifier_name)),
    [modifiers],
  );
  const imbuesByAbility = React.useMemo(() => {
    const byAbility = new Map<number, PlayerDetails["imbues"]["bindings"]>();
    for (const binding of modifiersEnabled ? details?.imbues.bindings ?? [] : []) {
      const list = byAbility.get(binding.ability_id) ?? [];
      list.push(binding);
      byAbility.set(binding.ability_id, list);
    }
    return byAbility;
  }, [details, modifiersEnabled]);

  // Pad to a fixed 10-slot inventory so empty slots stay visible.
  const slots = (items?.items ?? []).slice(0, SLOT_COUNT);
  while (slots.length < SLOT_COUNT) {
    slots.push({ ability_id: 0, ability_name: "" });
  }

  // Souls invested per category in the current inventory (sum of item costs).
  const investment = React.useMemo(() => {
    const t: Record<ItemCategory, number> = {
      weapon: 0,
      vitality: 0,
      spirit: 0,
    };
    for (const it of items?.items ?? []) {
      const stat = ITEM_STATS[it.ability_name];
      if (stat) t[stat.cat] += stat.cost;
    }
    return t;
  }, [items]);

  return (
    <div className="flex min-h-0 min-w-[20rem] flex-1 flex-col gap-3">
      <div className="flex flex-shrink-0 items-center gap-2">
        <button
          type="button"
          onClick={onBack}
          aria-label="Back to teams"
          className="flex size-7 flex-shrink-0 items-center justify-center rounded-md border border-border bg-card text-foreground transition-colors hover:bg-accent"
        >
          <ChevronLeft className="size-4" />
        </button>
        {portrait ? (
          <img
            src={portrait}
            alt={player.hero_name}
            width={32}
            height={32}
            className="size-8 flex-shrink-0 rounded object-contain"
          />
        ) : (
          <div className="size-8 flex-shrink-0 rounded bg-muted" />
        )}
        <div className="min-w-0 flex-1">
          <p className="truncate text-sm font-semibold leading-tight">
            {player.hero_name || "—"}
          </p>
          <p className="truncate text-xs text-muted-foreground leading-tight">
            {player.name || "—"}
          </p>
        </div>
        <RankBadge rank={player.rank} className="size-8" />
        <span
          className="text-xs font-semibold uppercase tracking-wide"
          style={{ color: teamColor }}
        >
          {teamLabel}
        </span>
      </div>

      <div className="flex min-h-0 flex-1 flex-col gap-3 overflow-y-auto pr-1">
        <CollapsibleSection
          title="Health"
          right={
            <span className="text-xs font-medium tabular-nums">
              <span className="text-foreground">{stats?.health ?? 0}</span>
              <span className="text-muted-foreground">
                {" / "}
                {stats?.max_health ?? 0}
              </span>
            </span>
          }
        >
          <HealthBar
            health={stats?.health ?? 0}
            maxHealth={stats?.max_health ?? 0}
          />
          <BarrierBar
            barrier={stats?.barrier ?? 0}
            maxBarrier={stats?.max_barrier ?? 0}
          />
        </CollapsibleSection>

        {abilities && abilities.length > 0 && (
          <CollapsibleSection title="Abilities">
            {!modifiersEnabled && <p className="mb-2 text-[10px] text-muted-foreground">Enable statuses/modifiers and reparse to view ability imbues. Recorded cooldowns remain available.</p>}
            <div className="flex gap-2">
              {abilities.map((a) => {
                const ac = abilityCooldowns?.get(a.ability_id);
                const isCharge = (ac?.maxCharges ?? 0) >= 2;
                const charge = isCharge
                  ? chargeAt(ac!.charges, regTick ?? tick ?? 0, ac!.maxCharges)
                  : null;
                // The ring shows the per-cast cooldown for all abilities —
                // including charge abilities (the between-cast lockout), where
                // it sits alongside the charge pills.
                const cd = activeCooldown(ac?.cooldowns, regTick ?? tick ?? 0);
                const imbues = imbuesByAbility.get(a.ability_id) ?? [];
                return (
                  <div
                    key={a.ability_id}
                    className="flex min-w-0 flex-1 flex-col items-center gap-1.5"
                  >
                    {/* Charge pills above the icon. The row is always present
                        (empty for non-charge abilities) so icons stay aligned. */}
                    <div className="flex h-1.5 w-full items-center justify-center gap-0.5">
                      {isCharge &&
                        Array.from({ length: ac!.maxCharges }, (_, i) => {
                          const full = charge ? i < charge.count : false;
                          const filling =
                            charge?.recharging && i === charge.count;
                          return (
                            <div
                              key={i}
                              className="h-full flex-1 overflow-hidden rounded-full bg-white/25"
                            >
                              {full ? (
                                <div className="h-full w-full bg-white" />
                              ) : filling ? (
                                <div
                                  className="h-full bg-white"
                                  style={{
                                    width: `${(charge?.progress ?? 0) * 100}%`,
                                  }}
                                />
                              ) : null}
                            </div>
                          );
                        })}
                    </div>
                    <Tooltip>
                      <TooltipTrigger asChild>
                        <div className="relative flex aspect-square w-full items-center justify-center rounded-md border border-border bg-muted/20">
                          <AbilityIcon
                            name={a.ability_name}
                            size={ABILITY_PIXELS}
                          />
                          {cd && (
                            <div className="pointer-events-none absolute inset-0 flex items-center justify-center">
                              {/* Semi-transparent pie that empties clockwise as
                                  the cooldown elapses (the wedge = time left). */}
                              <div
                                className="absolute inset-0 rounded-full"
                                style={{
                                  background: `conic-gradient(rgb(0 0 0 / 0.55) 0deg ${
                                    (cd.remaining / cd.total) * 360
                                  }deg, transparent ${
                                    (cd.remaining / cd.total) * 360
                                  }deg 360deg)`,
                                }}
                              />
                              <span className="relative text-xs font-bold tabular-nums text-white [text-shadow:0_1px_2px_rgb(0_0_0/0.95)]">
                                {cd.remaining >= 10
                                  ? Math.round(cd.remaining)
                                  : cd.remaining.toFixed(1)}
                              </span>
                            </div>
                          )}
                        </div>
                      </TooltipTrigger>
                      <TooltipContent>
                        {prettifyAbilityName(a.ability_name)}
                        {cd && ` · ${cd.remaining.toFixed(1)}s`}
                        {charge && ` · ${charge.count}/${ac!.maxCharges} charges`}
                        {imbues.map((binding) => (
                          <span key={binding.item_id} className="block text-purple-300">
                            Imbued by {itemDisplayName(abilityNameFromId(binding.item_id) ?? binding.item_name ?? "") || `item ${binding.item_id}`}
                          </span>
                        ))}
                      </TooltipContent>
                    </Tooltip>
                    <LevelBars
                      level={abilityLevels?.get(a.ability_id) ?? 0}
                      color={teamColor}
                    />
                    <div className="flex min-h-6 flex-wrap items-center justify-center gap-1" aria-label={imbues.length ? `Items imbuing ${prettifyAbilityName(a.ability_name)}` : undefined}>
                      {imbues.map((binding) => (
                        <ItemIcon
                          key={binding.item_id}
                          abilityId={binding.item_id}
                          abilityName={abilityNameFromId(binding.item_id) ?? binding.item_name ?? ""}
                          size={24}
                          className="border border-purple-300/70"
                        />
                      ))}
                    </div>
                  </div>
                );
              })}
            </div>
          </CollapsibleSection>
        )}

        {(visibleModifiers || !modifiersEnabled) && (
          <CollapsibleSection
            title="Modifiers"
            right={
              <span className="text-xs font-medium tabular-nums text-muted-foreground">
                {visibleModifiers?.length || ""}
              </span>
            }
          >
            {!modifiersEnabled ? <FeatureRequired feature="Statuses/modifiers" onEnable={onEnableModifiers} /> : <ModifierList
              modifiers={visibleModifiers ?? []}
              selfTeam={player.team}
              selfHeroId={player.hero_id}
              players={players}
              regTick={regTick ?? 0}
            />}
          </CollapsibleSection>
        )}

        <CollapsibleSection
          title="Items"
          right={
            <span className="flex items-center gap-2 text-xs font-semibold tabular-nums">
              <span
                style={{ color: CATEGORY_COLORS.weapon }}
                title={`Weapon: ${investment.weapon.toLocaleString()}`}
              >
                {formatSouls(investment.weapon)}
              </span>
              <span
                style={{ color: CATEGORY_COLORS.vitality }}
                title={`Vitality: ${investment.vitality.toLocaleString()}`}
              >
                {formatSouls(investment.vitality)}
              </span>
              <span
                style={{ color: CATEGORY_COLORS.spirit }}
                title={`Spirit: ${investment.spirit.toLocaleString()}`}
              >
                {formatSouls(investment.spirit)}
              </span>
            </span>
          }
        >
          <div className="grid grid-cols-5 place-items-center gap-2">
            {slots.map((it, i) =>
              it.ability_id ? (
                (() => {
                  // Frame each item in its category color (gun/vitality/spirit);
                  // border-box keeps the 48px footprint aligned with empty slots.
                  const cat = ITEM_STATS[it.ability_name]?.cat;
                  const color = cat ? CATEGORY_COLORS[cat] : undefined;
                  return (
                    <ItemIcon
                      key={`${i}-${it.ability_id}`}
                      abilityId={it.ability_id}
                      abilityName={it.ability_name}
                      size={ITEM_PIXELS}
                      className={cn("border-2", !color && "border-border")}
                      style={color ? { borderColor: color } : undefined}
                    />
                  );
                })()
              ) : (
                <div
                  key={`empty-${i}`}
                  style={{ width: ITEM_PIXELS, height: ITEM_PIXELS }}
                  className="rounded border border-border bg-muted/30"
                />
              ),
            )}
          </div>
        </CollapsibleSection>

        <CollapsibleSection
          title="Statuses"
          right={
            status?.states?.length ? (
              <span className="text-xs tabular-nums text-muted-foreground">
                {status.states.length}
              </span>
            ) : undefined
          }
        >
          {modifiersEnabled ? <StatusList status={status} /> : <FeatureRequired feature="Statuses/modifiers" onEnable={onEnableModifiers} />}
        </CollapsibleSection>

        <CollapsibleSection title="Permanent buffs">
          <PermanentBuffs totals={permanentBuffs} />
        </CollapsibleSection>

        <CollapsibleSection title="Hero stats">
          {catalog?.demoVersion && catalog.demoVersion !== catalog.version && (
            <p className="mb-2 text-[10px] text-amber-500">Demo build {catalog.demoVersion} uses catalog {catalog.version}; calculated stats may differ.</p>
          )}
          {!modifiersEnabled ? <FeatureRequired feature="Statuses/modifiers" onEnable={onEnableModifiers} /> : <HeroStats
            details={details}
            abilities={abilities}
            loading={detailsLoading}
            error={detailsError}
          />}
        </CollapsibleSection>
      </div>
    </div>
  );
}

// A bordered card whose body collapses when the header is clicked. `right` is
// optional trailing header content (e.g. the health value or item totals).
function CollapsibleSection({
  title,
  right,
  children,
}: {
  title: string;
  right?: React.ReactNode;
  children: React.ReactNode;
}) {
  const [open, setOpen] = React.useState(true);
  return (
    <section className="rounded-md border border-border bg-card p-3">
      <button
        type="button"
        onClick={() => setOpen((o) => !o)}
        aria-expanded={open}
        className="flex w-full items-center justify-between gap-2 text-left"
      >
        <span className="flex items-center gap-1 text-xs font-medium uppercase tracking-wide text-muted-foreground">
          <ChevronDown
            className={cn(
              "size-3.5 shrink-0 transition-transform",
              !open && "-rotate-90",
            )}
            aria-hidden
          />
          {title}
        </span>
        {right}
      </button>
      {open && <div className="mt-2">{children}</div>}
    </section>
  );
}

function BarrierBar({
  barrier,
  maxBarrier,
}: {
  barrier: number;
  maxBarrier: number;
}) {
  if (barrier <= 0) return null;
  return (
    <div className="mt-2 space-y-1 text-sky-400">
      <div className="flex items-center justify-between gap-2 text-xs">
        <span className="flex items-center gap-1">
          <Shield className="size-3" />Barrier
        </span>
        <span className="tabular-nums">
          {Math.round(barrier).toLocaleString()} / {Math.round(maxBarrier).toLocaleString()}
        </span>
      </div>
      <div
        role="progressbar"
        aria-label="Barrier"
        aria-valuemin={0}
        aria-valuemax={maxBarrier}
        aria-valuenow={barrier}
        title={`${barrier.toFixed(1)} / ${maxBarrier.toFixed(1)} recorded barrier HP`}
        className="h-2 overflow-hidden rounded-full bg-sky-400/15"
      >
        <div
          className="h-full rounded-full bg-sky-400"
          style={{ width: `${Math.min(100, 100 * barrier / maxBarrier)}%` }}
        />
      </div>
    </div>
  );
}

function HealthBar({
  health,
  maxHealth,
}: {
  health: number;
  maxHealth: number;
}) {
  const pct =
    maxHealth > 0
      ? Math.max(0, Math.min(1, health / maxHealth)) * 100
      : 0;
  // Hue shifts from green (full) to red (empty) — quick visual scan in
  // addition to the explicit numbers above.
  const hue = (pct / 100) * 120;
  const fill = pct > 0 ? `hsl(${hue} 70% 45%)` : "transparent";
  return (
    <div className="h-2 w-full overflow-hidden rounded-full bg-muted">
      <div
        className="h-full rounded-full transition-all"
        style={{ width: `${pct}%`, backgroundColor: fill }}
      />
    </div>
  );
}

// Three horizontally-stacked segments, `level` of them filled, showing how many
// upgrade tiers are spent on an ability (0 = unlocked / no tiers, up to 3).
function LevelBars({ level, color }: { level: number; color: string }) {
  return (
    <div
      className="flex w-full gap-0.5"
      title={level > 0 ? `Tier ${Math.min(level, ABILITY_TIERS)}` : "Unlocked"}
    >
      {Array.from({ length: ABILITY_TIERS }, (_, i) => (
        <span
          key={i}
          className={cn(
            "h-1.5 flex-1 rounded-sm",
            i < level ? "" : "bg-muted",
          )}
          style={i < level ? { backgroundColor: color } : undefined}
        />
      ))}
    </div>
  );
}

function QueryState({ loading, error }: { loading?: boolean; error?: string }) {
  if (loading) {
    return (
      <p className="flex items-center gap-2 text-xs text-muted-foreground">
        <Loader2 className="size-3.5 animate-spin" />
        Calculating this tick with Boon…
      </p>
    );
  }
  if (error) {
    return <p className="text-xs text-destructive">{error}</p>;
  }
  return <p className="text-xs text-muted-foreground">No data at this tick.</p>;
}

function statusLabel(value: string): string {
  return value
    .toLowerCase()
    .split("_")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join(" ");
}

function statusIcon(value: string): string {
  const name = value.toLowerCase();
  if (name.includes("silenc")) return "condition_silence";
  if (name.includes("stun")) return "condition_stun";
  if (name.includes("sleep")) return "condition_sleep";
  if (name.includes("immobil")) return "condition_immobilize";
  if (name.includes("knock")) return "condition_knockdown";
  if (name.includes("slow")) return "condition_slow";
  if (name.includes("burn")) return "condition_burn";
  if (name.includes("bleed")) return "condition_bleed";
  if (name.includes("toxic") || name.includes("poison")) return "condition_toxic";
  if (name.includes("curse")) return "condition_curse";
  if (name.includes("obscur") || name.includes("invis")) return "visibility";
  if (name.includes("invulner") || name.includes("immune")) return "armor";
  if (name.includes("sprint")) return "move_sprint";
  if (name.includes("slide")) return "move_slide";
  if (name.includes("zipline")) return "zipline";
  if (name.includes("dash")) return "move_dash";
  return "spirit";
}

function StatusPills({ values }: { values: string[] }) {
  return (
    <div className="flex flex-wrap gap-1.5">
      {values.map((value) => (
        <span
          key={value}
          title={value}
          className="flex items-center gap-1 rounded border border-border bg-muted/30 px-1.5 py-1 text-[10px]"
        >
          <img src={propertyIcon(statusIcon(value))} alt="" className="size-3 opacity-80" />
          {statusLabel(value)}
        </span>
      ))}
    </div>
  );
}

function StatusList({
  status,
}: {
  status?: PlayerStatus;
}) {
  if (!status?.states) return <p className="text-xs text-muted-foreground">No status data at this tick.</p>;
  // This recorded view includes modifier and movement states. Don't invent
  // precedence by merging the separate enabled/disabled inputs into it.
  const unknown = status.unknown_states.length;
  if (status.states.length === 0 && unknown === 0) {
    return <p className="text-xs text-muted-foreground">No active statuses.</p>;
  }
  return (
    <div className="space-y-2">
      <StatusPills values={status.states} />
      {unknown > 0 && (
        <p className="text-[10px] text-amber-500">
          {unknown} state bit{unknown === 1 ? "" : "s"} not named by this boon-data snapshot.
        </p>
      )}
    </div>
  );
}

const STAT_UNIT_SUFFIX: Record<string, string> = {
  "%": "%",
  multiplier: "×",
  "m/s": " m/s",
  m: " m",
  s: "s",
};

function formatStat(value: number | undefined, unit: string): string {
  if (value == null || !Number.isFinite(value)) return "—";
  const rounded = Math.abs(value) >= 100 ? value.toFixed(0) : value.toFixed(1).replace(/\.0$/, "");
  return `${rounded}${STAT_UNIT_SUFFIX[unit] ?? ""}`;
}

