// Reconstruct a readable label + icon hint from a span's source. Items are the
// `upgrade_*` family (great icon + localized-name coverage); everything else is
// a hero ability, with the modifier's own name as the last-resort label.
function modifierLabel(m: ModifierSpan): { label: string; isItem: boolean } {
  if (m.ability_name) {
    if (m.ability_name.startsWith("upgrade_")) {
      return { label: itemDisplayName(m.ability_name), isItem: true };
    }
    return { label: prettifyAbilityName(m.ability_name), isItem: false };
  }
  // Only the modifier's own name resolved — strip the modifier_ prefix and
  // reuse the ability prettifier for the rest.
  return {
    label: prettifyAbilityName(m.modifier_name.replace(/^modifier_/, "")),
    isItem: false,
  };
}

function ModifierList({
  modifiers,
  selfTeam,
  selfHeroId,
  players,
  regTick,
}: {
  modifiers: ModifierSpan[];
  selfTeam: number;
  selfHeroId: number;
  players?: PlayerInfo[];
  regTick: number;
}) {
  const heroById = React.useMemo(() => {
    const m = new Map<number, PlayerInfo>();
    for (const p of players ?? []) m.set(p.hero_id, p);
    return m;
  }, [players]);

  const rows = React.useMemo(() => {
    const serialRows = modifiers
      .map((modifier): ModifierRow | null => {
        const { label, isItem } = modifierLabel(modifier);
        if (!label) return null;
        const remaining =
          modifier.duration > 0
            ? Math.max(
                0,
                modifier.duration -
                  (regTick - modifier.applied_reg_tick) / TICKS_PER_SECOND,
              )
            : null;
        const casterTeam = heroById.get(modifier.caster_hero_id)?.team;
        return {
          key: `${modifier.serial}:${modifier.modifier_id}`,
          abilityId: modifier.ability_id,
          abilityName: modifier.ability_name,
          label,
          isItem,
          casterHeroId: modifier.caster_hero_id,
          stacks: modifier.stacks,
          remaining,
          incoming:
            modifier.caster_hero_id !== 0 &&
            modifier.caster_hero_id !== selfHeroId &&
            casterTeam != null &&
            casterTeam !== selfTeam,
        };
      })
      .filter((row): row is ModifierRow => row != null);

    return collapseModifierRows(serialRows, selfHeroId)
      .sort((a, b) => {
        if (a.incoming !== b.incoming) return a.incoming ? -1 : 1;
        const remaining = (a.remaining ?? Infinity) - (b.remaining ?? Infinity);
        return remaining || a.label.localeCompare(b.label);
      });
  }, [modifiers, heroById, selfTeam, selfHeroId, regTick]);
  if (rows.length === 0) {
    return (
      <p className="text-xs text-muted-foreground">No active modifiers.</p>
    );
  }

  return (
    <ul className="flex flex-col gap-1.5">
      {rows.map((r) => {
        const caster =
          r.casterHeroId && r.casterHeroId !== selfHeroId
            ? heroById.get(r.casterHeroId)
            : undefined;
        const multiplier = r.stacks > 1 ? r.stacks : 0;
        return (
          <li
            key={r.key}
            className={cn(
              "flex items-center gap-2 rounded-md border px-2 py-1.5",
              r.incoming
                ? "border-destructive/40 bg-destructive/5"
                : "border-border bg-muted/20",
            )}
          >
            <div className="flex size-7 flex-shrink-0 items-center justify-center">
              {r.isItem ? (
                <ItemIcon
                  abilityId={r.abilityId}
                  abilityName={r.abilityName}
                  size={26}
                  className="rounded"
                />
              ) : r.abilityName ? (
                <AbilityIcon name={r.abilityName} size={22} />
              ) : (
                <div className="size-5 rounded bg-muted/60" />
              )}
            </div>
            <div className="min-w-0 flex-1">
              <p className="truncate text-xs font-medium leading-tight">
                {r.label}
                {multiplier > 0 && (
                  <span className="ml-1 text-muted-foreground">
                    ×{multiplier}
                  </span>
                )}
              </p>
              {caster && (
                <p className="truncate text-[10px] leading-tight text-muted-foreground">
                  from {caster.hero_name || caster.name || "—"}
                </p>
              )}
            </div>
            {r.remaining != null && (
              <span className="flex-shrink-0 text-[10px] tabular-nums text-muted-foreground">
                {r.remaining < 0.1
                  ? "<0.1"
                  : r.remaining >= 10
                    ? Math.round(r.remaining)
                    : r.remaining.toFixed(1)}
                s
              </span>
            )}
          </li>
        );
      })}
    </ul>
  );
}
